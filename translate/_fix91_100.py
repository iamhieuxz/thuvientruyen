import re
from pathlib import Path

D = Path(r"F:\taitruyen\data\baojian_vi")

def fix(fn, reps, regexes=()):
    p = D / fn
    s = p.read_text(encoding="utf-8")
    orig = s
    for old, new, *cnt in reps:
        n = s.count(old)
        if n == 0:
            print(f"[MISS] {fn}: {old[:70]!r}")
            continue
        s = s.replace(old, new)
        print(f"[OK {n}] {fn}: {old[:50]!r}")
    for pat, new, expected in regexes:
        s2, n = re.subn(pat, new, s)
        if n == 0:
            print(f"[MISS-RE] {fn}: {pat}")
        else:
            print(f"[RE {n}] {fn}: {pat}")
        s = s2
    if s != orig:
        p.write_text(s, encoding="utf-8")
        print(f"--> wrote {fn}")

